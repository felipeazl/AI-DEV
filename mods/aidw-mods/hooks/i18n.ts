const DICT: Record<Lang, Record<Key, string>> = { en, 'pt-BR': ptBR }

let current: Lang = 'en'

/** Any `pt*` tag (`pt`, `pt-BR`, `pt_PT`) → pt-BR; anything else, or nothing → en. */
export function normalizeLang(tag: string | null | undefined): Lang {
  return /^pt\b|^pt[-_]/i.test((tag ?? '').trim()) ? 'pt-BR' : 'en'
}

export function setLang(tag: string | null | undefined): Lang {
  current = normalizeLang(tag)
  return current
}

export function getLang(): Lang {
  return current
}

/** The translated string, with `{name}` placeholders filled; a key missing in the language falls back to English. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICT[current][key] ?? en[key] ?? key
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

/** `t()` for a key built at run time (`sev.${severity}`); unknown keys give `fallback`. */
export function tk(key: string, fallback = '', vars: Record<string, string | number> = {}): string {
  return key in en ? t(key as Key, vars) : fallback
}

/** `[ui] language` of an `aidw.config.toml` text (a minimal TOML read: the section, then `language = "…"`). */
export function parseUiLanguage(toml: string): string | null {
  let section = ''
  for (const raw of toml.replace(/\r\n/g, '\n').split('\n')) {
    const line = raw.replace(/\s+#.*$/, '').trim()
    if (!line || line.startsWith('#')) continue
    const head = /^\[\s*([^\]]+?)\s*\]$/.exec(line)
    if (head) {
      section = head[1] ?? ''
      continue
    }
    if (section !== 'ui') continue
    const kv = /^language\s*=\s*(?:"([^"]*)"|'([^']*)'|(\S+))$/.exec(line)
    if (kv) return kv[1] ?? kv[2] ?? kv[3] ?? null
  }
  return null
}
